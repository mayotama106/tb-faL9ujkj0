/* 処理の流れの形式(ロジック作成)。見本のチケット(ファイルアップロード機能の構築)を入力して確かめる */
import { describe, expect, it } from "vitest";
import { GENRES } from "./genres";
import { buildTicket, type Values } from "./ticket";

const chk = (name: string, status = "", code = "", detail = "") => ({ name, status, code, detail });
const sample: Values = {
  title: "ファイルアップロード機能の構築（BE）",
  story_goal: "口座開設審査に必要な書類をオンラインでアップロードできる機能を提供したい",
  story_scope: "本チケットでは書類をアップロードする基本的な機能を実装する",
  story_refs: ["機能AのアップロードAPIを参照する（PUT：/account/applications/documents/:documentType）"],
  proc_name: "ファイルアップロード",
  flow: [
    { kind: "checks", text: "アップロードファイルの業務チェック", ac: "ミドルウェアでバリデーションチェックがされていること", items: [
      chk("0バイトファイルチェック", "400", "I009-00022"),
      chk("ファイルサイズ超過チェック"),
      chk("ファイル形式チェック", "400", "I009-00012", "拡張子が「.pdf」かどうか"),
      chk("ファイル名の存在チェック", "400", "E001-00002"),
      chk("ファイルデータの存在チェック", "400", "E001-00002")] },
    { kind: "checks", text: "リクエストバリデーションチェック", ac: "", items: [
      chk("パスパラメータBの存在チェック", "400", "E001-00002"),
      chk("パスパラメータBの13桁チェック", "400", "E001-00002"),
      chk("ファイル存在チェック", "400", "I009-00014")] },
    { kind: "do", text: "Xをキーにステータスを取得" },
    { kind: "if", text: "ステータスを元に編集可否をチェック", ac: "ステータスによる編集可否のチェックがされていること",
      yes: "編集可能", no: "編集不可", thenNone: true, then: [], else: [{ kind: "error", status: "", code: "" }] }
  ],
  deps: ["正式資材受領は11/17予定\nデザイン対応計画リンク"],
  branch: "開発ブランチはX面\nブランチ反映予定リンク"
};

const expected = `## ストーリー

* 口座開設審査に必要な書類をオンラインでアップロードできる機能を提供したい
* 本チケットでは書類をアップロードする基本的な機能を実装する
   * 機能AのアップロードAPIを参照する（PUT：/account/applications/documents/:documentType）

## ファイルアップロード処理
### 処理の流れ

1. アップロードファイルの業務チェック
   * 0バイトファイルチェック
   * ファイルサイズ超過チェック
   * ファイル形式チェック
      * 拡張子が「.pdf」かどうか
   * ファイル名の存在チェック
   * ファイルデータの存在チェック
2. リクエストバリデーションチェック
   * パスパラメータBの存在チェック
   * パスパラメータBの13桁チェック
   * ファイル存在チェック
3. Xをキーにステータスを取得
4. ステータスを元に編集可否をチェック
   * 編集可能であれば何もしない
   * 編集不可であればエラーを返却

## 受け入れ条件

* ミドルウェアでバリデーションチェックがされていること
   * 0バイトファイルチェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：I009-00022
   * ファイルサイズ超過チェックに引っかかる場合
      * HTTPステータス：【未記入】
      * エラーコード：【未記入】
   * ファイル形式チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：I009-00012
   * ファイル名の存在チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：E001-00002
   * ファイルデータの存在チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：E001-00002
* リクエストバリデーションチェックがされていること
   * パスパラメータBの存在チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：E001-00002
   * パスパラメータBの13桁チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：E001-00002
   * ファイル存在チェックに引っかかる場合
      * HTTPステータス：400
      * エラーコード：I009-00014
* ステータスによる編集可否のチェックがされていること
   * 編集不可の場合
      * HTTPステータス：【未記入】
      * エラーコード：【未記入】
* 正常に処理が完了した場合
   * HTTPステータス：【未記入】

## 制約事項・技術的補足
### 依存関係

* 正式資材受領は11/17予定
   * デザイン対応計画リンク

### ブランチ

* 開発ブランチはX面
   * ブランチ反映予定リンク`;

describe("処理の流れの形式", () => {
  it("見本のチケットと同じ形の本文を出し、抜けを未記入として数える", () => {
    const r = buildTicket(GENRES.logic, sample);
    expect(r.text).toBe(expected);
    /* サイズ超過の2件、編集不可の2件、正常時のステータス1件 */
    expect(r.missing).toBe(5);
    expect(r.blocks.map(b => [b.key, b.missing])).toEqual([["basic", 0], ["flow", 0], ["ac", 5], ["notes", 0]]);
  });
  it("空のチケットでは、各節に未記入を出す", () => {
    const r = buildTicket(GENRES.logic, {});
    expect(r.text).toContain("1. 【未記入】");
    expect(r.blocks.every(b => b.missing > 0)).toBe(true);
  });
  it("条件分岐の中の工程が複数なら、入れ子の箇条書きにする", () => {
    const r = buildTicket(GENRES.logic, { flow: [{ kind: "if", text: "残高を確認", yes: "足りる", no: "足りない",
      then: [{ kind: "do", text: "引き落とす" }, { kind: "do", text: "履歴を残す", detail: "取引IDを付ける" }],
      else: [{ kind: "error", status: "409", code: "E002-00001" }] }] });
    expect(r.text).toContain(["1. 残高を確認", "   * 足りるであれば", "      * 引き落とす", "      * 履歴を残す",
      "         * 取引IDを付ける", "   * 足りないであればエラーを返却"].join("\n"));
    expect(r.text).toContain(["* 残高を確認がされていること", "   * 足りないの場合", "      * HTTPステータス：409"].join("\n"));
  });
});
